import { describe, expect, it } from 'vitest';

import { formatAmount } from './format';

/**
 * formatAmount 的用例。
 *
 * 关注点不只是「正常值对不对」，而是**金额这种数据特有的那些坑**：
 * 分的进位、负数（退款）、0、以及浮点尾数会不会漏出来。
 */
describe('formatAmount', () => {
  it('把分格式化成元并补齐两位小数', () => {
    expect(formatAmount(0)).toBe('0.00 元');
    expect(formatAmount(1)).toBe('0.01 元');
    expect(formatAmount(99)).toBe('0.99 元');
    expect(formatAmount(100)).toBe('1.00 元');
    expect(formatAmount(1999)).toBe('19.99 元');
    expect(formatAmount(123456)).toBe('1234.56 元');
  });

  it('整元时不出现多余的小数尾巴', () => {
    // 「1000 分」若写成 10.0 元就会露出尾巴；这里要的是「10.00 元」。
    expect(formatAmount(1000)).toBe('10.00 元');
    expect(formatAmount(100000)).toBe('1000.00 元');
  });

  /**
   * 回归锁定：负数（退款场景）的符号只能出现一次，且在字符串最前。
   *
   * 这条用例**曾经会失败**（2026-10-08 发现、2026-10-09 修复）：当时实测得到 "-19.-99 元" ——
   * % 在 JS 里保留符号（-1999 % 100 === -99），padStart 只会补零、不会把负号挪走，
   * 于是拼出了不可能出现在账单上的字符串。
   *
   * 修复方式：先把符号摘出来单独存，对绝对值取整后做商余，再把符号补回去。
   * 别用 toFixed 绕（浮点尾数 + 舍入模式差异，见「非整数分」那条）。
   */
  it('负数（退款场景）应输出 -19.99 元而不是 "-19.-99 元"', () => {
    expect(formatAmount(-1)).toBe('-0.01 元');
    expect(formatAmount(-99)).toBe('-0.99 元');
    expect(formatAmount(-1999)).toBe('-19.99 元');
  });

  /**
   * 回归锁定：非整数分不应把浮点尾巴显示出来。
   *
   * 这条也曾会失败（2026-10-08 发现、2026-10-09 修复）：formatAmount(100.9) 当时得到
   * "1.0.9000000000000057 元" —— 余数是浮点数，padStart 完全不起作用。
   * 修复方式：让参与格式化的值先截断成整数分（Math.trunc；不要用 Math.round，
   * 它会把 199.5 的零头进位成 100、过不了下面的期望值），再走商余与 padStart。
   */
  it('非整数分不应把浮点尾巴显示出来', () => {
    expect(formatAmount(100.9)).toBe('1.00 元');
    expect(formatAmount(199.5)).toBe('1.99 元');
  });

  /**
   * 组合覆盖：负号与非整数分**同时**出现。
   *
   * 前面两条各只覆盖一个维度（负数是整数分、非整数分是正数），
   * 而「摘符号」与「截断」是同一条路径上的连续两步 ——
   * 组合场景单独立一条，把两个修复动作的合流行为锁死。
   */
  it('负数与非整数分组合时，符号与截断同时生效', () => {
    expect(formatAmount(-100.9)).toBe('-1.00 元');
    expect(formatAmount(-199.5)).toBe('-1.99 元');
  });

  /**
   * 这条是**回归锁定**，防止有人把实现改成`(amount / 100).toFixed(2)`：
   * 那种写法在正常整数分上看起来也对，但一旦遇上非整数分就暴露浮点尾数
   * （1.005 → "1.00"），而且 19.99 这种值在不同舍入模式下会有差异。
   * 本实现全程整数运算，所以这条现在通过。
   */
  it('正常整数分不产生浮点尾数', () => {
    for (const cents of [1, 7, 99, 105, 999, 1005, 1999, 1000001]) {
      expect(formatAmount(cents)).not.toMatch(/\d\.\d{3,}/);
    }
  });
});
